#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_all_54_jurisdictions_codified() {
        assert_eq!(LicensingEngine::ALL_STATE_CODES.len(), 54);
        for code in LicensingEngine::ALL_STATE_CODES.iter() {
            let rule = LicensingEngine::get_rule(code);
            assert_eq!(rule.state_code, *code);
            assert!(!rule.state_name.is_empty());
            assert!(!rule.regulatory_agency.is_empty());
            assert!(!rule.bond_amount.is_empty());
            assert!(!rule.statutory_code.is_empty());
            assert!(!rule.notes.is_empty());
        }
    }

    #[test]
    fn test_texas_mandatory_bond_rule() {
        let tx = LicensingEngine::get_rule("TX");
        assert!(!tx.requires_license);
        assert!(tx.requires_surety_bond);
        assert_eq!(tx.bond_amount, "$10,000");
        assert!(tx.unlicensed_collection_is_per_se_violation);
        assert!(tx.statutory_code.contains("392.101"));
    }

    #[test]
    fn test_california_dcla_licensing() {
        let ca = LicensingEngine::get_rule("CA");
        assert!(ca.requires_license);
        assert!(ca.requires_surety_bond);
        assert_eq!(ca.bond_amount, "$25,000");
        assert!(ca.statutory_code.contains("Debt Collection Licensing Act"));
    }

    #[test]
    fn test_new_jersey_bond_filing() {
        let nj = LicensingEngine::get_rule("NJ");
        assert!(nj.requires_surety_bond);
        assert_eq!(nj.bond_amount, "$5,000");
        assert!(nj.statutory_code.contains("45:18-1"));
    }
}
